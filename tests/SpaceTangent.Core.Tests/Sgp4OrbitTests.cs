public sealed class Sgp4OrbitTests
{
    [Theory]
    [InlineData(double.MaxValue)]
    [InlineData(-double.MaxValue)]
    [InlineData(double.NaN)]
    [InlineData(double.PositiveInfinity)]
    [InlineData(2000000.01)]
    public void ResonantPropagationRejectsUnboundedWork(double minutes)
    {
        string row = File.ReadLines(Path.Combine(AppContext.BaseDirectory, "Fixtures", "sgp4-verification-reference.csv"))
            .First(line => line.StartsWith("1 08195", StringComparison.Ordinal));
        string[] tle = row.Split('|');
        var orbit = new Sgp4Orbit(TwoLineElements.Parse(tle[0], tle[1]));
        Assert.Throws<ArgumentOutOfRangeException>(() => orbit.Propagate(minutes, out _));
    }

    private const string JasonFirst = "1 26997U 01055A   11192.81984987 -.00000038  00000-0  10000-3 0  3699";
    private const string JasonSecond = "2 26997  66.0463 303.1838 0007562 261.9351  98.0768 12.80928955448691";
    private const string SorceFirst = "1 27651U 03004A   11193.17002924  .00000232  00000-0  43749-4 0  5408";
    private const string SorceSecond = "2 27651  39.9965 107.7032 0026765 200.0544 159.9185 14.82697678458356";

    public static IEnumerable<object[]> ReferenceStates() =>
        File.ReadLines(Path.Combine(AppContext.BaseDirectory, "Fixtures", "sgp4-reference.csv"))
            .Where(line => !line.StartsWith('#')).Select(line => new object[] { line });

    [Theory]
    [MemberData(nameof(ReferenceStates))]
    public void RealTlesMatchIndependentTemeStates(string row)
    {
        string[] fields = row.Split(',');
        double[] values = fields.Skip(1).Select(value => double.Parse(value, CultureInfo.InvariantCulture)).ToArray();
        var orbit = new Sgp4Orbit(fields[0] == "Jason-1" ? TwoLineElements.Parse(JasonFirst, JasonSecond) :
            TwoLineElements.Parse(SorceFirst, SorceSecond));
        var expectedPosition = new Vector3d(values[1], values[2], values[3]);
        var expectedVelocity = new Vector3d(values[4], values[5], values[6]);

        Assert.True(orbit.TrySample(orbit.Epoch.AddSeconds(values[0]), out var state));
        Assert.InRange((state.PositionKilometers - expectedPosition).Length, 0, 1e-5);
        Assert.InRange((state.VelocityKilometersPerSecond - expectedVelocity).Length, 0, 1e-8);
        Assert.Equal(new FrameId("teme-of-date"), Sgp4Orbit.Frame);
    }

    private const double VerificationPositionKilometers = 1e-6, VerificationVelocityKilometersPerSecond = 1e-9;

    public static IEnumerable<object[]> VerificationCases()
    {
        string path = Path.Combine(AppContext.BaseDirectory, "Fixtures", "sgp4-verification-reference.csv");
        return File.ReadLines(path).Select((line, index) => (line, index)).Where(item => IsCase(item.line))
            .Select(item => new object[] { item.index, item.line[2..7].Trim() });
    }

    // Vallado's SGP4-VER cases, generated by tools/reference/generate_sgp4_verification.py from the published
    // C++ code in AFSPC mode and cross-checked with CSPICE EVSGP4. A port differs only by rounding, so the
    // tolerance is 1 mm and 1e-9 km/s even after years of propagation.
    [Theory]
    [MemberData(nameof(VerificationCases))]
    public void PublishedVerificationCasesMatchTheReferenceImplementation(int firstLine, string catalogNumber)
    {
        string path = Path.Combine(AppContext.BaseDirectory, "Fixtures", "sgp4-verification-reference.csv");
        var lines = File.ReadLines(path).Skip(firstLine).ToArray();
        string[] tle = lines[0].Split('|');
        var elements = TwoLineElements.Parse(tle[0], tle[1]);
        Sgp4Orbit? orbit = null;
        int checkedRows = 0;
        foreach (string row in lines.Skip(1).TakeWhile(line => !IsCase(line)))
        {
            string[] fields = row.Split(',');
            double minutes = double.Parse(fields[0], CultureInfo.InvariantCulture);
            var expectedStatus = (Sgp4Status)int.Parse(fields[1], CultureInfo.InvariantCulture);
            if (minutes == 0 && expectedStatus is not (Sgp4Status.Ok or Sgp4Status.Decayed))
            {
                Assert.Throws<ArgumentException>(() => new Sgp4Orbit(elements));
                return;
            }
            orbit ??= new Sgp4Orbit(elements);
            Sgp4Status status = orbit.Propagate(minutes, out var state);
            Assert.True(expectedStatus == status, $"{catalogNumber} at {minutes} min: {status}, expected {expectedStatus}.");
            checkedRows++;
            if (fields[2].Length == 0)
                continue;
            double[] values = fields[2..].Select(value => double.Parse(value, CultureInfo.InvariantCulture)).ToArray();
            double position = (state.PositionKilometers - new Vector3d(values[0], values[1], values[2])).Length;
            double velocity = (state.VelocityKilometersPerSecond - new Vector3d(values[3], values[4], values[5])).Length;
            Assert.True(position <= VerificationPositionKilometers, $"{catalogNumber} at {minutes} min: {position} km.");
            Assert.True(velocity <= VerificationVelocityKilometersPerSecond, $"{catalogNumber} at {minutes} min: {velocity} km/s.");
        }
        Assert.True(checkedRows > 0);
    }

    private static bool IsCase(string line) => line.StartsWith("1 ", StringComparison.Ordinal) && line.Contains('|');

    [Fact]
    public void ColdResonanceCheckpointsAreIdenticalUnderConcurrentQueries()
    {
        string[] tle = File.ReadLines(Path.Combine(AppContext.BaseDirectory, "Fixtures", "sgp4-verification-reference.csv"))
            .First(line => line.StartsWith("1 08195", StringComparison.Ordinal)).Split('|');
        var elements = TwoLineElements.Parse(tle[0], tle[1]);
        var shared = new Sgp4Orbit(elements);
        double[] times = [525000, -524000, 720 * 64 - .5, 720 * 64, -720 * 64, 1845100, -100000];
        Parallel.For(0, 56, index =>
        {
            double time = times[index % times.Length];
            var independent = new Sgp4Orbit(elements);
            Assert.Equal(independent.Propagate(time, out var expected), shared.Propagate(time, out var actual));
            Assert.Equal(expected, actual);
        });
    }

    [Fact]
    public void DeepSpaceStatesDoNotDependOnQueryOrder()
    {
        // MOLNIYA 2-14 (12 h resonance) and EUTELSAT 1-F1 (24 h resonance) from the verification set.
        var orbits = File.ReadLines(Path.Combine(AppContext.BaseDirectory, "Fixtures", "sgp4-verification-reference.csv"))
            .Where(line => line.StartsWith("1 08195", StringComparison.Ordinal) || line.StartsWith("1 14128", StringComparison.Ordinal))
            .Select(line => line.Split('|')).Select(tle => new Sgp4Orbit(TwoLineElements.Parse(tle[0], tle[1]))).ToArray();
        double[] minutes = [0, 2880, -1440, 30, 100_000, 719.5, 720, 720.5, -5000, 2880];
        foreach (var orbit in orbits)
        {
            Assert.True(orbit.DeepSpace);
            var forward = minutes.Select(value => State(orbit, value)).ToArray();
            var shuffled = minutes.Select((value, index) => (value, index)).Reverse()
                .Select(item => (item.index, State(orbit, item.value))).OrderBy(item => item.index).Select(item => item.Item2);
            Assert.Equal(forward, shuffled);
        }

        static CartesianState State(Sgp4Orbit orbit, double minutes)
        {
            Assert.Equal(Sgp4Status.Ok, orbit.Propagate(minutes, out var state));
            return state;
        }
    }

    [Fact]
    public void ExactlyEquatorialGeostationaryElementsPropagate()
    {
        const string first = "1 99999U 20001A   26100.50000000  .00000000  00000-0  00000-0 0  9990";
        const string second = "2 99999   0.0000  80.0000 0001000 100.0000 200.0000  1.00270000    10";
        var orbit = new Sgp4Orbit(TwoLineElements.Parse(WithChecksum(first), WithChecksum(second)));
        Assert.True(orbit.DeepSpace);
        foreach (double days in new[] { 0, .25, 1, 30, 200 })
        {
            Assert.True(orbit.TrySample(orbit.Epoch.AddSeconds(days * 86_400), out var state));
            Assert.InRange(state.PositionKilometers.Length, 42_000, 42_350);
            // Lunar-solar forcing tilts a geostationary orbit by under 1 degree per year.
            Assert.InRange(Math.Abs(state.PositionKilometers.Z), 0, 42_350 * Math.Sin((.02 + days / 365) * Math.PI / 180));
        }

        static string WithChecksum(string line)
        {
            int sum = line[..68].Sum(character => char.IsAsciiDigit(character) ? character - '0' : character == '-' ? 1 : 0);
            return line[..68] + (char)('0' + sum % 10);
        }
    }

    [Fact]
    public void JasonEpochRetainsTheExactTleDayFraction()
    {
        TwoLineElements elements = TwoLineElements.Parse(JasonFirst, JasonSecond);
        Assert.Equal("26997", elements.CatalogNumber);
        Assert.Equal(new UtcDateTime(new DateOnly(2011, 7, 11), 19, 40, 35, 28_768_000), elements.UtcEpoch);
        var orbit = new Sgp4Orbit(elements);
        Assert.Equal(elements.UtcEpoch, TimeConversion.ToUtc(orbit.Epoch));
        Assert.False(orbit.TrySample(orbit.Epoch.AddSeconds(366 * 86_400), out _));
        Assert.Throws<ArgumentException>(() => orbit.TrySample(new JulianInstant(orbit.Epoch.Day, 0, TimeScale.Tt), out _));
    }

    [Fact]
    public void RejectsInvalidLineChecksumAndMismatchedCatalogNumbers()
    {
        Assert.Throws<FormatException>(() => TwoLineElements.Parse(JasonFirst[..^1] + "0", JasonSecond));
        Assert.Throws<FormatException>(() => TwoLineElements.Parse(JasonFirst, SorceSecond));
    }
}
