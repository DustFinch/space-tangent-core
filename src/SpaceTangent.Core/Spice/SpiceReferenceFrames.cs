    private static readonly Dictionary<string, int> Names = Inertial.Select((frame, index) => (frame.Name, Id: index + 1))
        .Concat(BodyFrames.Select(frame => (frame.Name, frame.Id)))
        .ToDictionary(frame => frame.Name, frame => frame.Id, StringComparer.OrdinalIgnoreCase);

    private static readonly Dictionary<int, (string Name, int Body)> Bodies =
        BodyFrames.ToDictionary(frame => frame.Id, frame => (frame.Name, frame.Body));

    internal static int Id(string name) => Names.GetValueOrDefault(name);
    internal static (string Name, int Body) Body(int id) => Bodies.GetValueOrDefault(id);
    internal static Basis3d? InertialBasis(int id) => id > 0 && id <= Inertial.Length ? Inertial[id - 1].ToJ2000 : null;
